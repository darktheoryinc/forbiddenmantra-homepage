// Walk-through of laugh markers, show verdicts, import and bit cap. Usage: node tests/e2e-features.cjs [baseUrl]
const { chromium } = require('playwright')
const base = process.argv[2] || 'http://localhost:8787'
const out = process.env.SHOTS || '/tmp/claude-0/shots'
const step = (m) => console.log('•', m)
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m) }
;(async () => {
  const b = await chromium.launch({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] })
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, permissions: ['microphone'] })
  const p = await ctx.newPage(); const errors = []
  p.on('pageerror', (e) => errors.push(String(e))); p.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
  await p.goto(base + '/#/vault')

  step('import notes into Vault')
  await p.getByRole('button', { name: 'Import' }).click()
  await p.getByLabel('Notes to import').fill('Airport pretzels cost eleven dollars. It is flour and regret.\n\nMy mother hated flying; she said God would have given us better snacks.\n\n- Dating apps are a fish convention\n- I have never wanted to date a fish')
  await p.getByRole('button', { name: /^Import \d/ }).click()
  await p.waitForSelector('text=Imported 4')
  assert((await p.locator('a.card-link').count()) === 4, 'four imported jokes')

  step('build a set from the vault')
  await p.getByRole('link', { name: 'Sets' }).click()
  await p.getByRole('button', { name: '+ New set' }).click()
  await p.getByLabel('Title').fill('Friday late show'); await p.getByRole('button', { name: 'Create set' }).click()
  await p.waitForSelector('text=Set Builder')
  await p.getByRole('button', { name: 'Suggest jokes to fill' }).click()
  await p.waitForSelector('text=Suggested')

  step('rehearse with laugh markers')
  await p.getByRole('link', { name: /Rehearse/ }).click()
  await p.getByRole('button', { name: '● Record rehearsal' }).click()
  await p.getByRole('button', { name: /Big laugh/ }).waitFor()
  await p.getByRole('button', { name: /Big laugh/ }).click()
  await p.getByRole('button', { name: /Next/ }).click()
  await p.getByRole('button', { name: /Silence/ }).click()
  await p.waitForTimeout(1500)
  await p.screenshot({ path: `${out}/10-stage-markers.png` })
  await p.getByRole('button', { name: /Stop recording/ }).click()
  await p.waitForSelector('text=Rehearsal recording saved')
  await p.getByRole('link', { name: /Exit/ }).click()
  await p.locator('section:has(h3:text("Rehearsals")) a').first().click()
  await p.waitForSelector('text=Laugh markers')
  const marks = await p.locator('text=/▶ 0:0/').count()
  step(`markers on recording: ${marks}`); assert(marks === 2, 'two markers saved')
  await p.screenshot({ path: `${out}/11-markers.png`, fullPage: true })
  await p.getByRole('button', { name: '+ 😂 Laugh' }).click()
  await p.waitForFunction(() => document.body.innerText.match(/▶ 0:0/g)?.length === 3, null, { timeout: 5000 }).catch(() => assert(false, 'manual marker added'))

  step('log show with per-bit results')
  await p.goto(base + '/#/shows')
  await p.getByRole('button', { name: '+ Log show' }).click()
  await p.getByLabel('Venue').fill('The Cellar'); await p.locator('#ps').selectOption({ index: 1 })
  await p.waitForSelector('text=How did each bit land?')
  await p.getByRole('group', { name: /Result for/ }).first().getByRole('button', { name: /Hit/ }).click()
  await p.screenshot({ path: `${out}/12-verdicts.png` })
  await p.getByRole('button', { name: 'Save', exact: true }).click()
  await p.waitForSelector('text=The Cellar')
  await p.goto(base + '/#/vault'); await p.waitForSelector('text=1/1 hit')

  step('bit cap warning')
  await p.goto(base + '/#/settings'); await p.getByLabel(/Warn when one bit/).fill('15')
  await p.waitForTimeout(300)
  await p.getByRole('link', { name: 'Done' }).click()
  await p.goto(base + '/#/vault'); await p.locator('a.card-link').first().click()
  await p.getByLabel('The bit').fill(Array(70).fill('word').join(' '))
  await p.waitForSelector('text=over your 15s cap')
  await p.screenshot({ path: `${out}/13-cap.png` })

  console.log('console/page errors:', errors.length ? errors : 'none')
  await b.close()
})().catch((e) => { console.error('E2E FAILED', e.message); process.exit(1) })
