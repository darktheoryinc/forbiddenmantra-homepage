#!/usr/bin/env node
// Collects Amazon identifiers that Open Library itself lists on edition records (identifiers.amazon), from the harvest HTTP caches.
// Offline: reads staging/harvest*/.cache/ol/*.json (already downloaded), writes data/asin-hints.json = { isbn13: { asin, olKey } }.
// Nothing here is fetched from Amazon. The importer applies a hint only when it is consistent with the edition (see scripts/import.mjs).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = {};
for (const dir of fs.readdirSync(path.join(ROOT, 'staging')).filter((d) => d.startsWith('harvest'))) {
  const cache = path.join(ROOT, 'staging', dir, '.cache/ol');
  if (!fs.existsSync(cache)) continue;
  for (const f of fs.readdirSync(cache)) {
    let j; try { j = JSON.parse(fs.readFileSync(path.join(cache, f), 'utf8')); } catch { continue; }
    for (const [k, v] of Object.entries(j)) {
      if (!k.startsWith('ISBN:')) continue;
      const a = (v?.details?.identifiers?.amazon ?? []).find((x) => /^(B[0-9A-Z]{9}|[0-9]{9}[0-9X])$/.test(x));
      if (a) out[k.slice(5)] = { asin: a, olKey: v.details.key ?? null };
    }
  }
}
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(path.join(ROOT, 'data/asin-hints.json'), JSON.stringify({ _doc: 'Amazon identifiers listed on Open Library edition records (not verified against Amazon). Generated by scripts/asin-hints.mjs from the harvest caches.', hints: sorted }, null, 0));
console.log(`asin hints: ${Object.keys(sorted).length}`);
