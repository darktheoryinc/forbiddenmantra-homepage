def stacked(theme='dark'):
    wm, spans = wordmark(['Forbidden', 'Mantra'], 330, gap=0.86, theme=theme)
    R = 318; pad = 70; ring_w = 2 * (R + 60); gapx = 40
    Wd = ring_w + gapx + wm.width; Hd = max(ring_w, wm.height + 60)
    cv = Image.new('RGBA', (Wd, Hd), (0, 0, 0, 0)); cx, cy = ring_w // 2, Hd // 2
    cv.alpha_composite(ring_layer((Wd, Hd), cx, cy, R))
    cv.alpha_composite(emblem, (cx - W // 2, cy - H // 2))
    wy = (Hd - wm.height) // 2; cv.alpha_composite(wm, (ring_w + gapx, wy))
    rl = rule_layer(int(wm.width * 0.80)); cv.alpha_composite(rl, (ring_w + gapx + (wm.width - rl.width) // 2, wy + wm.height - 40))
    return cv
