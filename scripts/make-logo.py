# ---------- 2. metallic wordmark ----------
def wordmark(lines, size, gap=0.92, pad=70, align='center', theme='dark'):
    T_ = THEMES[theme]
    f = ImageFont.truetype(FONT, size); asc, desc = f.getmetrics(); lh = int(size * gap)
    widths = [f.getlength(t) for t in lines]; Wd = int(max(widths)) + pad * 2; Hd = lh * len(lines) + int(desc * 1.2) + pad * 2
    SS = 2; big = Image.new('L', (Wd * SS, Hd * SS), 0); d = ImageDraw.Draw(big); fb = ImageFont.truetype(FONT, size * SS)
    spans = []
    for i, t in enumerate(lines):
        x = pad * SS + (int(max(widths) * SS - f.getlength(t) * SS) // 2 if align == 'center' else 0); y = (pad + i * lh) * SS
        d.text((x, y), t, font=fb, fill=255); bb = d.textbbox((x, y), t, font=fb); spans.append((bb[1] // SS, bb[3] // SS))
    mask = np.asarray(big.resize((Wd, Hd), Image.LANCZOS)).astype(float) / 255
    yy, xx = np.mgrid[0:Hd, 0:Wd]
    t = np.zeros((Hd, Wd))
    for (y0, y1) in spans:
        sel = (yy >= y0 - lh * 0.1) & (yy <= y1 + lh * 0.1); t[sel] = ((yy - y0) / max(1, (y1 - y0)))[sel]
    base = lerp_stops(t, T_['stops'])
    b = gauss(mask, 2.4); gy, gx = np.gradient(b); sh = -(gx + gy) * 1.6
    hi = np.clip(sh, 0, 1)[..., None]; lo = np.clip(-sh, 0, 1)[..., None]
    col = base * (1 - 0.40 * lo) + 255 * T_['hi'] * hi
    sheen = np.exp(-(((xx * 0.55 + yy * 0.9) - Wd * 0.62) / (Wd * 0.07)) ** 2) * 0.16
    col = col + (255 - col) * sheen[..., None]
    bottom = np.clip((t - 0.78) / 0.22, 0, 1)[..., None] * 0.20; col = col * (1 - bottom) + EMERALD * bottom      # faint emerald reflected light at the base of each letter
    col = np.clip(col, 0, 255)
    rim = np.clip(dilate(mask, 2) - mask, 0, 1); glow = gauss(dilate(mask, 5), 16) * T_['glow']
    out = np.zeros((Hd, Wd, 4))
    out[..., :3] = TEAL_GLOW; out[..., 3] = glow
    # composite rim then fill (straight-alpha "over")
    def over(dst, rgb, a):
        a = a[..., None]; da = dst[..., 3:4]; oa = a + da * (1 - a)
        rgbn = (np.array(rgb) * a + dst[..., :3] * da * (1 - a)) / np.maximum(oa, 1e-6)
        dst[..., :3] = rgbn; dst[..., 3:4] = oa
    over(out, T_['rim'], rim * T_['rim_a'])
    over(out, col, mask)
    out[..., 3] *= 255
    return Image.fromarray(np.clip(out, 0, 255).astype('uint8'), 'RGBA'), spans

# ---------- 3. delicate accents ----------
def ring_layer(size, cx, cy, R):
    SS = 3; im = Image.new('RGBA', (size[0] * SS, size[1] * SS), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    gold = (232, 196, 90, 235); em = (47, 214, 180, 200)
    box = lambda r: [(cx - r) * SS, (cy - r) * SS, (cx + r) * SS, (cy + r) * SS]
    gaps = [(-100, -80), (-10, 10), (80, 100), (170, 190)]       # clear the arcs at the four nodes
    def arcs(r, color, w):
        segs = [(-80, -10), (10, 80), (100, 170), (190, 260)]
        for a0, a1 in segs: d.arc(box(r), a0, a1, fill=color, width=w * SS)
    arcs(R, gold, 3); arcs(R + 14, em, 2)
    for ang in (-90, 0, 90, 180):
        x = cx + R * math.cos(math.radians(ang)); y = cy + R * math.sin(math.radians(ang))
        d.ellipse([(x - 9) * SS, (y - 9) * SS, (x + 9) * SS, (y + 9) * SS], fill=(240, 205, 100, 255)); d.ellipse([(x - 4) * SS, (y - 4) * SS, (x + 4) * SS, (y + 4) * SS], fill=(24, 120, 108, 255))
        for k in (-1, 1):                                          # fine four-point sparkle strokes
            dx, dy = math.cos(math.radians(ang)), math.sin(math.radians(ang))
            d.line([(x + dx * 14 * k * SS / SS) * SS, (y + dy * 14 * k) * SS, (x + dx * 34 * k) * SS, (y + dy * 34 * k) * SS], fill=(247, 226, 150, 190), width=2 * SS)
    layer = im.resize(size, Image.LANCZOS)
    glow = layer.filter(ImageFilter.GaussianBlur(10)); ga = np.asarray(glow).copy(); ga[..., :3] = (20, 179, 156); ga[..., 3] = (ga[..., 3] * 0.55).astype('uint8')
    return Image.alpha_composite(Image.fromarray(ga, 'RGBA'), layer)
def rule_layer(w, h=26):
    SS = 3; im = Image.new('RGBA', (w * SS, h * SS), (0, 0, 0, 0)); d = ImageDraw.Draw(im); y = h * SS // 2
    for x in range(w * SS):
        u = x / (w * SS); fade = math.sin(math.pi * u) ** 0.8; d.point((x, y), fill=(232, 196, 90, int(230 * fade))); d.point((x, y + 1), fill=(232, 196, 90, int(230 * fade)))
    cx = w * SS // 2; d.polygon([(cx, y - 9 * SS), (cx + 7 * SS, y), (cx, y + 9 * SS), (cx - 7 * SS, y)], fill=(240, 205, 100, 255)); d.ellipse([cx - 3 * SS, y - 3 * SS, cx + 3 * SS, y + 3 * SS], fill=(24, 120, 108, 255))
    return im.resize((w, h), Image.LANCZOS)

