def gauss(a, r): return np.asarray(Image.fromarray((np.clip(a, 0, 1) * 255).astype('uint8')).filter(ImageFilter.GaussianBlur(r))).astype(float) / 255
def dilate(a, n): return np.asarray(Image.fromarray((np.clip(a, 0, 1) * 255).astype('uint8')).filter(ImageFilter.MaxFilter(n * 2 + 1))).astype(float) / 255
def lerp_stops(t, stops):
    t = np.clip(t, 0, 1); out = np.zeros(t.shape + (3,))
    for i in range(len(stops) - 1):
        (t0, c0), (t1, c1) = stops[i], stops[i + 1]; sel = (t >= t0) & (t <= t1); u = ((t - t0) / (t1 - t0 + 1e-9))[sel][:, None]
        out[sel] = np.array(c0) * (1 - u) + np.array(c1) * u
    return out
