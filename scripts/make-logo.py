    cv.alpha_composite(em, (0, yb)); cv.alpha_composite(wm, (em.width + 28, (cv.height - wm.height) // 2))
    s = height_px / cv.height; return cv.resize((round(cv.width * s), height_px), Image.LANCZOS)
